export interface BillingPlan {
  code: PlanCode
  name: string
  monthlyCredits: number
  /** null = unlimited seats */
  seatLimit: number | null
  priceUsdCents: number
}

export type SubscriptionStatus = "ACTIVE" | "TRIALING" | "PAST_DUE" | "CANCELED"
export type PaymentProviderCode = "STRIPE" | "CHAPA"
/** Provider names accepted by POST /billing/checkout */
export type CheckoutProvider = "stripe" | "chapa"

export interface WalletSubscription {
  status: SubscriptionStatus
  currentPeriodEnd: string | null
  cancelAtPeriodEnd: boolean
  provider: PaymentProviderCode | null
}

export interface Wallet {
  balance: number
  plan: BillingPlan
  subscription: WalletSubscription | null
  /** limit null = unlimited */
  seats: { used: number; limit: number | null }
}

export interface CreditPackage {
  id: string
  code: string
  name: string
  credits: number
  bonusCredits: number
  totalCredits: number
  /** Minor units (cents). etb null/0 = no ETB price */
  prices: { usd: number; etb: number | null }
}

export interface BillingProviders {
  stripe: boolean
  chapa: boolean
}

export interface MomentumPricing {
  publishBase: number
  featureCost: number
  featureDays: number
  aiRerunCost: number
  /** Seeker side: credits per job application. */
  applyCost: number
  /** Recruiter credits to message a seeker found in talent search. */
  outreachCost: number
  /** Seeker credits to apply to a job from the web (once per job). */
  externalApplyCost: number
  /** Seeker AI tools (credits per run). */
  resumeTailorCost: number
  mockInterviewCost: number
  negotiationAdviceCost: number
  /** What the platform offers right now (server-side switches). */
  features: { ai: boolean; webJobs: boolean }
}

export type CreditTransactionType =
  | "PURCHASE"
  | "SIGNUP_BONUS"
  | "PLAN_GRANT"
  | "JOB_PUBLISH"
  | "JOB_FEATURE"
  | "AI_ANALYSIS"
  | "APPLICATION"
  | "OUTREACH"
  | "EXTERNAL_APPLY"
  | "AI_SEEKER_TOOL"
  | "REFUND"
  | "ADJUSTMENT"

export const CREDIT_TRANSACTION_LABEL: Record<CreditTransactionType, string> = {
  PURCHASE: "Credit purchase",
  SIGNUP_BONUS: "Sign-up bonus",
  PLAN_GRANT: "Monthly plan credits",
  JOB_PUBLISH: "Job published",
  JOB_FEATURE: "Job featured",
  AI_ANALYSIS: "AI analysis",
  APPLICATION: "Job application",
  OUTREACH: "Candidate outreach",
  EXTERNAL_APPLY: "Web job application",
  AI_SEEKER_TOOL: "AI career tool",
  REFUND: "Refund",
  ADJUSTMENT: "Adjustment",
}

export interface CreditTransaction {
  id: string
  /** Signed: + credit, - debit */
  amount: number
  type: CreditTransactionType
  balanceAfter: number
  referenceId: string | null
  note: string | null
  actor: { id: string; name: string } | null
  createdAt: string
}

export type PaymentStatus = "PENDING" | "SUCCEEDED" | "FAILED" | "REFUNDED"

export interface BillingPayment {
  id: string
  provider: PaymentProviderCode
  kind: "CREDIT_PACK" | "SUBSCRIPTION"
  description: string
  credits: number
  /** Minor units */
  amount: number
  currency: string
  status: PaymentStatus
  createdAt: string
  paidAt: string | null
}

export interface PublishCostInput {
  remote?: boolean
  salaryMax?: number | null
  salaryCurrency?: string | null
  salaryPeriod?: SalaryPeriodCode | null
  categoryId?: string
}

export interface PublishCost {
  cost: number
  balance: number
  breakdown: { base: number; multipliers: { name: string; factor: number }[] }
}

export interface FeatureJobResult {
  featuredUntil: string
  balance: number
}

// ─── State Interface ───────────────────────────────────────────────────────────

export interface JobState {
  // ── Recruiter workspace ──────────────────────────────────────────────────
  jobs: Job[]
  candidates: Candidate[]
  selectedJobId: string
  activeView: RecruiterView
  careerSelectedJobId: string
  workspaceName: string
  isAddCandidateOpen: boolean
  addCandidateColumn: Candidate["status"]
  isAddJobOpen: boolean
  searchQuery: string
  theme: UserTheme
  notifications: NotificationItem[]
  selectedCandidateId: string | null
  team: TeamMember[]

  // ── Loading ──────────────────────────────────────────────────────────────
  isInitialLoading: boolean
  initialLoadError: string | null

  // ── Auth ─────────────────────────────────────────────────────────────────
  user: AuthUser | null
  accessToken: string | null
  isAuthenticated: boolean
  authLoading: boolean
  authError: string | null
  socket: Socket | null
  liveEvent: LiveEvent | null

  // ── Auth actions ─────────────────────────────────────────────────────────
  /** Set while a password login waits for the second factor. */
  mfaPending: { mfaToken: string } | null
  /**
   * true = signed in; false = failed (authError set); "MFA_REQUIRED" = call verifyTwoFactorLogin;
   * "CAPTCHA_REQUIRED" = show the captcha and retry with its token.
   */
  loginUser: (email: string, password: string, captchaToken?: string) => Promise<LoginResult>
  /** Completes a pending MFA login with a TOTP or recovery code. Sets authError on failure. */
  verifyTwoFactorLogin: (code: string) => Promise<boolean>
  /** Abandons a pending MFA login (back to the password form). */
  cancelTwoFactorLogin: () => void
  registerUser: (
    name: string,
    email: string,
    password: string,
    role: "SEEKER" | "RECRUITER",
    captchaToken?: string,
    extras?: RegisterExtras
  ) => Promise<boolean>
  /** Reloads emailVerified / twoFactorEnabled (and name/avatar) from /auth/me. */
  refreshAuthUser: () => Promise<void>
  verifyEmail: (token: string) => Promise<void>
  resendVerification: () => Promise<void>
  requestPasswordReset: (email: string, captchaToken?: string) => Promise<void>
  resetPassword: (token: string, password: string) => Promise<void>
  /** Changes the password and keeps the current session using the fresh token. */
  changePassword: (currentPassword: string, newPassword: string) => Promise<void>
  startTwoFactorSetup: () => Promise<TwoFactorSetup>
  /** Returns the 10 one-time recovery codes (shown once). */
  enableTwoFactor: (code: string) => Promise<string[]>
  disableTwoFactor: (code: string, password?: string) => Promise<void>
  regenerateRecoveryCodes: (code: string) => Promise<string[]>
  /** Downloads a JSON export of the user's data. */
  exportMyData: () => Promise<void>
  logout: () => Promise<void>
  /** Why the user was signed out (e.g. suspension), shown on the sign-in page. */
  signedOutReason: string | null
  signOutWithReason: (reason: string) => Promise<void>
  clearSignedOutReason: () => void
  /** Reloads company status + support e-mail from /auth/me. */
  loadAccount: () => Promise<void>
  /** Swaps the access token (login, restore, silent refresh). Never loads workspace data. */
  setAccessToken: (token: string | null) => void
  initializeSocket: () => void
  deleteAccount: (password?: string) => Promise<void>

  // ── Recruiter actions ────────────────────────────────────────────────────
  selectJob: (jobId: string) => void
  moveCandidate: (candidateId: string, targetStatus: Candidate["status"]) => Promise<void>
  addCandidate: (jobId: string, input: NewCandidateInput) => Promise<Candidate>
  addJob: (job: {
    title: string
    location: string
    type: string
    salaryMin?: number | null
    salaryMax?: number | null
    salaryCurrency?: string | null
    salaryPeriod?: SalaryPeriodCode | null
    description: string
    requirements: string[]
    skills: string[]
    benefits?: string[]
    categoryId: string
    remote?: boolean
    /** Defaults to ACTIVE on the server; DRAFT saves without publishing. */
    status?: "ACTIVE" | "DRAFT"
  }) => Promise<Job>
  updateJob: (jobId: string, patch: Partial<JobUpdatePatch>) => Promise<void>
  deleteJob: (jobId: string) => Promise<void>
  toggleBookmark: (candidateId: string) => Promise<void>
  setSearchQuery: (query: string) => void
  setTheme: (theme: UserTheme) => Promise<void>
  toggleTheme: () => Promise<void>
  fetchNotifications: () => Promise<void>
  markNotificationsAsRead: () => Promise<void>
  markAllNotificationsRead: () => Promise<void>
  markNotificationRead: (id: string) => Promise<void>
  clearNotifications: () => Promise<void>
  deleteCandidate: (candidateId: string) => Promise<void>
  setActiveView: (view: RecruiterView) => void
  setCareerSelectedJobId: (jobId: string) => void
  applyToJob: (jobId: string, input?: ApplyInput) => Promise<void>
  setWorkspaceName: (name: string) => void
  setAddCandidateOpen: (open: boolean, col?: Candidate["status"]) => void
  setAddJobOpen: (open: boolean) => void
  setSelectedCandidateId: (id: string | null) => void
  fetchInitialData: (options?: { force?: boolean }) => Promise<void>
  fetchSeekerDashboard: () => Promise<void>

  // ── Team ─────────────────────────────────────────────────────────────────
  fetchTeam: () => Promise<void>
  removeTeamMember: (memberId: string) => Promise<void>
  /** Owner: open invites and pending join requests. */
  teamInvites: TeamInvite[]
  joinRequests: TeamJoinRequest[]
  fetchTeamInvites: () => Promise<void>
  fetchJoinRequests: () => Promise<void>
  /** Owner: e-mails an accept link (402 SEAT_LIMIT_REACHED when the plan is full). */
  inviteTeamMember: (email: string, role: AssignableTeamRole) => Promise<void>
  resendInvite: (inviteId: string) => Promise<void>
  revokeInvite: (inviteId: string) => Promise<void>
  approveJoinRequest: (requestId: string, role: AssignableTeamRole) => Promise<void>
  declineJoinRequest: (requestId: string) => Promise<void>
  transferOwnership: (memberId: string) => Promise<void>
  /** Member leaves the company (owners transfer first); they then set up or join a company. */
  leaveTeam: () => Promise<void>
  /** Recruiters without a company (OAuth sign-up, left a team). Reloads the workspace. */
  setupCompany: (data: { name: string; website?: string }) => Promise<void>
  previewInvite: (token: string) => Promise<InvitePreview>
  acceptInvite: (token: string) => Promise<void>
  declineInvite: (token: string) => Promise<void>
  /** A verified company on the e-mail's domain, or null. */
  findCompanyByEmail: (email: string) => Promise<CompanyMatch | null>
  myJoinRequest: MyJoinRequest | null
  fetchMyJoinRequest: () => Promise<void>
  requestToJoin: (companyId: string) => Promise<void>
  cancelJoinRequest: () => Promise<void>

  // ── Seeker workspace ─────────────────────────────────────────────────────
  candidateActiveView: SeekerView
  publicJobs: PublicJob[]
  recommendedJobs: PublicJob[]
  seekerDashboard: SeekerDashboardData | null
  publicJobsLoading: boolean
  jobApplications: JobApplication[]
  discoverSearch: string
  discoverTypeFilter: string
  seekerProfile: SeekerProfileData | null
  setCandidateActiveView: (view: SeekerView) => void
  fetchApplications: () => Promise<void>
  toggleJobBookmark: (id: string) => Promise<void>
  applyFromDiscover: (publicJobId: string, input?: ApplyInput) => Promise<void>
  saveJobFromDiscover: (publicJobId: string) => Promise<void>
  withdrawApplication: (applicationId: string) => Promise<void>
  setDiscoverSearch: (q: string) => void
  setDiscoverTypeFilter: (t: string) => void
  reportJob: (jobId: string, reason: JobReportReason, details?: string) => Promise<void>

  // ── Calendar ─────────────────────────────────────────────────────────────
  events: CalendarEvent[]
  eventsLoading: boolean
  fetchEvents: () => Promise<void>
  createEvent: (data: Omit<CalendarEvent, "id">) => Promise<void>
  deleteEvent: (id: string) => Promise<void>

  // ── Interview invites (candidate picks a time) ──────────────────────────
  /** Seeker: their open/booked invites. Recruiter: invites of applications opened in the sheet. */
  interviewInvites: InterviewInvite[]
  fetchInterviewInvites: (applicationId?: string) => Promise<void>
  createInterviewInvite: (input: NewInterviewInvite) => Promise<InterviewInvite>
  bookInterviewSlot: (inviteId: string, slotId: string) => Promise<void>
  cancelInterviewInvite: (inviteId: string) => Promise<void>
  /** Socket: insert or replace an invite (and its booked event). */
  upsertInterviewInvite: (invite: any, event?: any) => void

  // ── Seeker AI tools ──────────────────────────────────────────────────────
  /** Saved tailoring for a job, or null. */
  fetchCvTailoring: (jobId: string) => Promise<CvTailoring | null>
  /** Runs (or reopens) CV tailoring; charges resumeTailorCost unless saved, refunded if AI fails. */
  tailorCv: (jobId: string, rerun?: boolean) => Promise<CvTailoring>

  fetchSalaryBenchmark: (title: string, currency: string) => Promise<SalaryBenchmark>
  /** Charges negotiationAdviceCost (refunded if the AI fails). */
  getNegotiationAdvice: (offerId: string) => Promise<NegotiationAdvice>
  fetchSkillOverview: () => Promise<SkillOverviewItem[]>
  startSkillTest: (skill: string) => Promise<SkillTest>
  submitSkillTest: (id: string, answers: number[]) => Promise<SkillTestResult>
  fetchMockInterviews: () => Promise<MockInterview[]>
  /** Charges mockInterviewCost (refunded if question generation fails). */
  startMockInterview: (jobId: string) => Promise<MockInterview>
  answerMockQuestion: (id: string, index: number, answer: string) => Promise<MockInterview>

  // ── Jobs from the web (seekers) ─────────────────────────────────────────
  fetchWebJobs: (
    q?: string,
    remote?: boolean,
    cursor?: string,
    filters?: JobFilterInput,
    refresh?: boolean
  ) => Promise<{ items: WebJob[]; nextCursor: string | null }>
  /** Charges the external apply cost once; returns the original posting URL. */
  applyWebJob: (id: string) => Promise<{ url: string; charged: number; alreadyApplied: boolean }>

  // ── External job tracker (seekers) ───────────────────────────────────────
  externalApplications: ExternalApplication[]
  fetchExternalApplications: () => Promise<void>
  addExternalApplication: (
    input: ExternalApplicationInput & { company: string; title: string }
  ) => Promise<void>
  updateExternalApplication: (id: string, patch: ExternalApplicationInput) => Promise<void>
  removeExternalApplication: (id: string) => Promise<void>

  // ── Talent search (recruiters) and outreach answers (seekers) ───────────
  searchTalent: (q?: string, location?: string) => Promise<{ total: number; results: TalentCard[] }>
  fetchTalentProfile: (seekerId: string) => Promise<TalentProfile>
  /** Debits the company's outreach cost and adds a "Reached out" card. */
  reachOut: (seekerId: string, jobId: string, message: string) => Promise<void>
  talentVisibility: TalentVisibility | null
  fetchTalentVisibility: () => Promise<void>
  setTalentVisibility: (open: boolean) => Promise<void>
  unblockCompany: (companyId: string) => Promise<void>
  respondToOutreach: (applicationId: string, interested: boolean) => Promise<void>
  blockOutreachCompany: (applicationId: string) => Promise<void>

  // ── Offers ───────────────────────────────────────────────────────────────
  /** Seeker: their offers. Recruiter: offers of applications opened in the panel. */
  offers: Offer[]
  fetchOffers: (applicationId?: string) => Promise<void>
  sendOffer: (input: OfferInput) => Promise<Offer>
  acceptOffer: (offerId: string, signatureName: string) => Promise<void>
  declineOffer: (offerId: string, reason?: string) => Promise<void>
  withdrawOffer: (offerId: string) => Promise<void>
  upsertOffer: (raw: any) => void

  // ── Scorecards (hiring team only) ────────────────────────────────────────
  fetchScorecards: (applicationId: string) => Promise<ScorecardView>
  submitScorecard: (applicationId: string, input: ScorecardInput) => Promise<ScorecardView>
  setScorecardCompetencies: (jobId: string, competencies: string[]) => Promise<string[]>

  // ── Documents ────────────────────────────────────────────────────────────
  documents: Document[]
  documentsLoading: boolean
  fetchDocuments: () => Promise<void>
  uploadDocument: (meta: { name: string; type: string; size: string; url: string }) => Promise<void>
  toggleDocumentActive: (id: string) => Promise<void>
  deleteDocument: (id: string) => Promise<void>

  // ── Messages ─────────────────────────────────────────────────────────────
  conversations: ConversationThread[]
  conversationsLoading: boolean
  activeConversationId: string | null
  conversationMessages: ChatMessage[]
  messagesLoading: boolean
  /** Header data for the open thread (also for draft threads that have no messages yet) */
  activeThreadMeta: ConversationThread | null
  typingByThread: Record<string, TypingState>
  fetchConversations: () => Promise<void>
  /** Opens a thread: joins the room, loads meta + messages, marks it read. */
  openConversation: (applicationId: string) => Promise<void>
  /** Closes the open thread and leaves its room. */
  leaveConversation: () => void
  /** @deprecated alias of openConversation */
  fetchMessages: (applicationId: string) => Promise<void>
  sendMessage: (applicationId: string, text: string) => Promise<void>
  retryMessage: (applicationId: string, clientId: string) => Promise<void>
  sendTyping: (applicationId: string, isTyping: boolean) => void
  markConversationRead: (applicationId: string) => Promise<void>
  /** @deprecated thin alias: id → openConversation, null → leaveConversation */
  setActiveConversation: (id: string | null) => void
  deleteConversation: (applicationId: string) => Promise<void>
  unreadMessageCount: number
  fetchUnreadCount: () => Promise<void>

  // ── AI candidate analysis ────────────────────────────────────────────────
  analyzeCandidate: (candidateId: string) => Promise<void>

  // ── AI Chat ──────────────────────────────────────────────────────────────
  aiChatMessages: AiChatMessage[]
  aiChatLoading: boolean
  aiChatOpen: boolean
  sendAiChat: (message: string) => Promise<void>
  clearAiChat: () => void
  setAiChatOpen: (open: boolean) => void

  // ── Profile ──────────────────────────────────────────────────────────────
  profileUpdating: boolean
  updateProfile: (data: ProfileUpdateInput) => Promise<void>

  // ── Seeker tools (matching, alerts, saved searches, CV import) ───────────
  matchedJobs: PublicJob[]
  matchTab: MatchTab
  matchedJobsLoading: boolean
  /** 0-100, from /matching/jobs and GET /profile */
  profileStrength: number
  /** Human-readable missing profile items, from GET /profile */
  profileMissing: string[]
  /** No skills and no title: matches are meaningless */
  thinProfile: boolean
  /** Loads page one of a tab; `filters` replaces the active Discover filters (kept otherwise). */
  fetchMatchedJobs: (
    tab: MatchTab,
    filters?: JobFilterInput,
    opts?: { refresh?: boolean }
  ) => Promise<void>
  /** Discover filters applied server-side to the matched list. */
  matchFilters: JobFilterInput
  /** Cursor of the next matched-jobs page; null = no more pages. */
  matchedJobsCursor: string | null
  matchedJobsLoadingMore: boolean
  /** Appends the next page of the current tab (no-op while loading or at the end). */
  fetchMoreMatchedJobs: () => Promise<void>
  /** Reloads profileStrength / profileMissing from GET /profile. */
  refreshProfileStrength: () => Promise<void>
  alerts: JobAlertItem[]
  alertsLoading: boolean
  fetchAlerts: () => Promise<void>
  createAlert: (input: JobAlertInput) => Promise<JobAlertItem>
  updateAlert: (id: string, patch: Partial<JobAlertInput> & { active?: boolean }) => Promise<void>
  deleteAlert: (id: string) => Promise<void>
  savedSearches: SavedSearchItem[]
  fetchSavedSearches: () => Promise<void>
  createSavedSearch: (input: SavedSearchInput) => Promise<SavedSearchItem>
  updateSavedSearch: (id: string, patch: Partial<SavedSearchInput>) => Promise<void>
  deleteSavedSearch: (id: string) => Promise<void>
  /** Never writes the profile: returns suggestions for the seeker to review. */
  importProfileFromCv: (input: { documentId?: string; url?: string }) => Promise<CvSuggestions>
  fetchScreeningQuestions: (jobId: string) => Promise<ScreeningQuestion[]>
  /** Stage history of an application (seeker: no actor names). */
  fetchTimeline: (applicationId: string) => Promise<TimelineEntry[]>

  // ── Recruiter pipeline ───────────────────────────────────────────────────
  fetchJobQuestions: (jobId: string) => Promise<ScreeningQuestion[]>
  saveJobQuestions: (jobId: string, questions: ScreeningQuestion[]) => Promise<ScreeningQuestion[]>
  fetchNotes: (applicationId: string) => Promise<CandidateNote[]>
  addNote: (applicationId: string, body: string) => Promise<CandidateNote>
  updateNote: (noteId: string, body: string) => Promise<CandidateNote>
  deleteNote: (noteId: string) => Promise<void>
  labels: CandidateLabel[]
  fetchLabels: () => Promise<void>
  createLabel: (name: string, color: string) => Promise<CandidateLabel>
  updateLabel: (id: string, patch: { name?: string; color?: string }) => Promise<void>
  deleteLabel: (id: string) => Promise<void>
  setCandidateLabels: (applicationId: string, labelIds: string[]) => Promise<void>
  labelFilter: string | null
  setLabelFilter: (labelId: string | null) => void
  /** Per-item results; successful changes are applied to local state. */
  bulkUpdateCandidates: (input: BulkUpdateInput) => Promise<BulkResult[]>
  funnelAnalytics: FunnelAnalytics | null
  fetchFunnelAnalytics: (jobId?: string) => Promise<void>
  companyProfile: CompanyProfile | null
  fetchCompanyProfile: () => Promise<void>
  updateCompanyProfile: (patch: CompanyProfilePatch) => Promise<void>

  // ── Momentum (credits & billing, recruiter) ──────────────────────────────
  wallet: Wallet | null
  creditPackages: CreditPackage[]
  plans: BillingPlan[]
  billingProviders: BillingProviders | null
  pricing: MomentumPricing | null
  transactions: CreditTransaction[]
  /** null = no more pages (or not loaded yet) */
  transactionsCursor: string | null
  payments: BillingPayment[]
  fetchWallet: () => Promise<void>
  /** Packages + plans + configured providers + pricing. */
  fetchBillingCatalog: () => Promise<void>
  /** reset=true reloads the first page; otherwise appends the next page. */
  fetchTransactions: (reset?: boolean) => Promise<void>
  fetchPayments: () => Promise<void>
  /** Creates a checkout and redirects the browser to the provider. */
  startCheckout: (packageId: string, provider: CheckoutProvider) => Promise<void>
  /** OWNER only; redirects to Stripe Checkout. */
  subscribeToPlan: (planCode: PlanCode) => Promise<void>
  /** OWNER only; redirects to the Stripe billing portal. */
  openBillingPortal: () => Promise<void>
  /** Re-checks a pending payment with the provider; refreshes the wallet when it succeeded. */
  confirmPayment: (paymentId: string) => Promise<BillingPayment>
  getPublishCost: (input: PublishCostInput) => Promise<PublishCost>
  featureJob: (jobId: string, days: number) => Promise<FeatureJobResult>
}
