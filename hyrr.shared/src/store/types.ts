export interface Job {
  id: string
  title: string
  location: string
  type: string
  posted: string
  /** "Flagged" = hidden after user reports; shown as "Under review" */
  status: "Active" | "Closed" | "Draft" | "Flagged"
  color: "purple" | "blue" | "green" | "orange"
  description: string
  requirements: string[]
  /** The posting company passed domain verification */
  companyVerified: boolean
  remote?: boolean
  /** Display text generated by the server from the structured range below */
  salary?: string
  salaryMin?: number | null
  salaryMax?: number | null
  salaryCurrency?: string | null
  salaryPeriod?: SalaryPeriodCode | null
  categoryId?: string
  /** Paid feature flag; currently featured when featuredUntil is in the future */
  featured?: boolean
  featuredUntil?: string | null
  /** First publish time (null = never published, so publishing will cost credits) */
  publishedAt?: string | null
  /** Set when Hyrr moderation removed the job; it can't be edited or reopened. */
  removedAt?: string | null
  removedReason?: string | null
  /** Credits charged when the job was first published */
  momentumCost?: number
}

